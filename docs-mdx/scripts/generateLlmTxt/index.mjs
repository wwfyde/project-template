#!/usr/bin/env node
/* eslint-disable no-await-in-loop */
/* eslint-disable no-console */

import fs from 'fs/promises';
import path from 'path';
import { pathToFileURL } from 'url';
import { globby } from 'globby';
import * as prettier from 'prettier';
import { unified } from 'unified';
import remarkParse from 'remark-parse';
import remarkGfm from 'remark-gfm';
import remarkStringify from 'remark-stringify';
import { visit } from 'unist-util-visit';
import { createFileContent } from './createFileContent.mjs';
import { mdxToMarkdown } from './mdxToMarkdown.mjs';
import { resolveUrl, isAbsoluteUrl } from './resolver.mjs';
import { siteConfig } from '../../src/site.config.mjs';

const PROJECT_ROOT = path.resolve(import.meta.dirname, '../..');
const MDX_SOURCE_DIR = path.join(PROJECT_ROOT, 'src/app/(docs)/react');
// Production Markdown must reflect the API tables generated by next build.
const OUTPUT_BASE_DIR = path.join(
  PROJECT_ROOT,
  process.argv.includes('--export') ? 'out' : 'public',
);

const NETLIFY_DEPLOYMENT_URL =
  process.env.PULL_REQUEST === 'true' ? process.env.DEPLOY_PRIME_URL : process.env.URL;

function incrementHeaders(increment = 1) {
  return (tree) => {
    visit(tree, 'heading', (node) => {
      node.depth = Math.min(node.depth + increment, 6);
    });
  };
}

function inlineCodeHtmlTags(text) {
  return text.replace(/<\/?[a-zA-Z][^>]*>/g, '`$&`');
}

function githubSlugify(text) {
  return text
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}_\s-]/gu, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function resolveRelativeLinks({ base, metadataByUrl }) {
  return (tree) => {
    visit(tree, 'link', (node) => {
      if (!node.url || isAbsoluteUrl(node.url)) {
        return;
      }

      const urlPath = node.url.endsWith('.md') ? node.url.slice(0, -3) : node.url;
      const metadata = metadataByUrl.get(urlPath);
      node.url = metadata ? `#${githubSlugify(metadata.title)}` : resolveUrl(node.url, base);
    });
  };
}

async function prepareForInlineMarkdown(markdown, metadataByUrl, baseUrl) {
  const result = await unified()
    .use(remarkParse)
    .use(remarkGfm)
    .use(incrementHeaders, 2)
    .use(resolveRelativeLinks, { base: baseUrl, metadataByUrl })
    .use(remarkStringify)
    .process(markdown);
  return String(result.value);
}

async function removeEmptyDirectories(directory) {
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      const child = path.join(directory, entry.name);
      await removeEmptyDirectories(child);
      if ((await fs.readdir(child)).length === 0) {
        await fs.rmdir(child);
      }
    }
  }
}

/**
 * Discover documentation articles and export Markdown, including demos and API tables.
 * Section index pages supply section titles; new sections need no generator changes.
 */
export async function generateLlmsTxt({
  sourceDir = MDX_SOURCE_DIR,
  outputDir = OUTPUT_BASE_DIR,
  baseUrl = NETLIFY_DEPLOYMENT_URL || '/',
} = {}) {
  console.log('Generating llms.txt and markdown files...');

  const outputReactDir = path.join(outputDir, 'react');
  await fs.mkdir(outputReactDir, { recursive: true });

  const mdxFiles = await globby('**/page.mdx', { cwd: sourceDir });
  // The root and section indexes are navigation pages, not duplicate articles.
  const articleFiles = mdxFiles.filter((file) => file.split('/').length > 2).sort();
  const mdxFilesInfo = articleFiles.map((relativePath) => {
    const dirPath = path.dirname(relativePath);
    const urlPath = `/react/${dirPath.replace(/\\/g, '/')}`;
    return {
      sectionName: relativePath.split('/')[0],
      urlPath,
      mdxFile: path.join(sourceDir, relativePath),
      outputFilePath: path.join(outputReactDir, `${dirPath}.md`),
    };
  });
  const urlsWithMdVersion = new Set(mdxFilesInfo.map((info) => info.urlPath));
  const metadataByUrl = new Map();
  const sections = new Map();

  for (const { sectionName, urlPath, mdxFile, outputFilePath } of mdxFilesInfo) {
    if (!sections.has(sectionName)) {
      const sectionIndex = path.join(sourceDir, sectionName, 'page.mdx');
      const indexContent = mdxFiles.includes(`${sectionName}/page.mdx`)
        ? await fs.readFile(sectionIndex, 'utf-8')
        : '';
      const sectionTitle = indexContent.match(/^#\s+(.+)$/m)?.[1];
      sections.set(sectionName, {
        title:
          sectionTitle ||
          sectionName.replace(
            /(^|-)(\w)/g,
            (_, prefix, letter) => `${prefix ? ' ' : ''}${letter.toUpperCase()}`,
          ),
        pages: [],
      });
    }

    const mdxContent = await fs.readFile(mdxFile, 'utf-8');
    const { markdown, title, subtitle, description } = await mdxToMarkdown(mdxContent, mdxFile, {
      urlPath,
      urlsWithMdVersion,
    });
    const frontmatter = [
      '---',
      `title: ${JSON.stringify(title || 'Untitled')}`,
      subtitle ? `subtitle: ${JSON.stringify(subtitle)}` : null,
      description ? `description: ${JSON.stringify(description)}` : null,
      '---',
    ]
      .filter(Boolean)
      .join('\n');
    const prettierOptions = await prettier.resolveConfig(outputFilePath);
    const content = await prettier.format([frontmatter, '', markdown].join('\n'), {
      ...prettierOptions,
      filepath: outputFilePath,
      parser: 'markdown',
    });

    await fs.mkdir(path.dirname(outputFilePath), { recursive: true });
    await fs.writeFile(outputFilePath, content, 'utf-8');

    const pageMeta = {
      title: title || 'Untitled',
      description: description || '',
      urlPath,
      mdUrlPath: `${urlPath}.md`,
      fullMarkdown: markdown,
    };
    sections.get(sectionName).pages.push(pageMeta);
    metadataByUrl.set(urlPath, pageMeta);
  }

  // Removed or renamed source pages must disappear from exports as well. Keep
  // HTML and other assets untouched when operating on a static build directory.
  const currentOutputs = new Set(mdxFilesInfo.map((info) => info.outputFilePath));
  const existingOutputs = await globby('**/*.md', { cwd: outputReactDir, absolute: true });
  await Promise.all(
    existingOutputs.filter((file) => !currentOutputs.has(file)).map((file) => fs.unlink(file)),
  );
  await removeEmptyDirectories(outputReactDir);

  const structure = { sections: [...sections.values()] };
  const preamble = [`# ${siteConfig.name}`, '', siteConfig.description, ''];
  const renderPageAsLink = (page) => [
    `- [${page.title}](${resolveUrl(page.mdUrlPath, baseUrl)}): ${inlineCodeHtmlTags(page.description)}`,
  ];
  const renderPageAsRelativeLink = (page) => [
    `- [${page.title}](.${page.mdUrlPath}): ${inlineCodeHtmlTags(page.description)}`,
  ];
  const renderPageAsInline = async (page) => [
    await prepareForInlineMarkdown(page.fullMarkdown, metadataByUrl, baseUrl),
  ];

  const createFile = async (filename, pageRenderer, { formatPages = false } = {}) => {
    const filePath = path.join(outputDir, filename);
    const content = await createFileContent({
      structure,
      preamble,
      pageRenderer,
      filePath,
      formatPages,
    });
    await fs.writeFile(filePath, content, 'utf-8');
  };

  await Promise.all([
    createFile('llms.txt', renderPageAsLink),
    createFile('llms-full.txt', renderPageAsInline, { formatPages: true }),
    createFile('index.md', renderPageAsRelativeLink),
  ]);

  console.log(
    `Successfully generated ${mdxFilesInfo.length} markdown files, llms.txt, llms-full.txt, and index.md`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  generateLlmsTxt().catch((error) => {
    console.error('Error generating llms.txt:', error);
    process.exitCode = 1;
  });
}
