async (page) => {
  const check = (value, message) => { if (!value) throw new Error(message) }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '展开侧栏' }).click()
  await page.getByRole('dialog').waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '展开侧栏')
  check(await page.getByRole('button', { name: '展开侧栏' }).evaluate((node) => node === document.activeElement), 'Mobile drawer must restore focus')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('tab', { name: '对话', exact: true }).click()
  await page.getByRole('textbox', { name: '消息内容' }).fill('保留对话草稿')
  await page.getByRole('tab', { name: '任务', exact: true }).click()
  await page.getByRole('textbox', { name: '消息内容' }).fill('保留任务草稿')
  await page.getByRole('tab', { name: '对话', exact: true }).click()
  check(await page.getByRole('textbox', { name: '消息内容' }).inputValue() === '保留对话草稿', 'Chat draft must survive mode switch')
  await page.getByRole('textbox', { name: '消息内容' }).press('Enter')
  await page.getByRole('button', { name: '停止预览' }).waitFor()
  check(await page.getByRole('textbox', { name: '消息内容' }).evaluate((node) => node === document.activeElement), 'Initial submit must keep composer focus')
  await page.getByRole('textbox', { name: '消息内容' }).fill('下一条消息')
  await page.getByRole('button', { name: '停止预览' }).click()
  check(await page.getByRole('textbox', { name: '消息内容' }).inputValue() === '下一条消息', 'Stopping must preserve the next draft')
  await page.getByRole('tab', { name: '任务', exact: true }).click()
  check(await page.getByRole('textbox', { name: '消息内容' }).inputValue() === '保留任务草稿', 'Task draft must survive mode switch')
  await page.getByRole('button', { name: '选择模型' }).click()
  await page.getByRole('menuitemradio', { name: /快速回答/ }).click()
  check(await page.getByRole('button', { name: '选择模型' }).textContent() === '快速回答', 'Model selection must update')
  await page.getByRole('button', { name: '工具', exact: true }).click()
  await page.getByRole('menuitemcheckbox', { name: /联网搜索/ }).click()
  await page.keyboard.press('Escape')
  await page.getByRole('textbox', { name: '消息内容' }).press('Enter')
  await page.getByRole('button', { name: '停止预览' }).waitFor({ state: 'hidden', timeout: 10000 })
  check((await page.getByRole('article', { name: 'Agent', exact: true }).last().textContent()).includes('仅预览'), 'Tool selections must remain clearly preview-only')
  await page.getByRole('button', { name: '搜索对话', exact: true }).click()
  await page.getByRole('textbox', { name: '搜索对话' }).fill('不存在的对话')
  check(await page.getByText('没有找到相关对话').isVisible(), 'Search must filter and show no-results state')
  await page.getByRole('textbox', { name: '搜索对话' }).press('Escape')
  await page.keyboard.press('Control+k')
  check(await page.getByRole('button', { name: '开始任务' }).isDisabled(), 'New task must reset its draft')
  await page.setViewportSize({ width: 390, height: 844 })
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile page must not overflow horizontally')
  console.log('PASS: drawer focus, mode drafts, initial submit focus, stop, model, tools, task completion, search, new task, mobile overflow')
}
